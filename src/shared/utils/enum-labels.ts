const variants: Record<
  "assignment" | "area" | "conversation" | "job",
  Readonly<Record<string, string>>
> = {
  assignment: { COMPLETED: "Completada" },
  area: { ACTIVE: "Activa", INACTIVE: "Inactiva" },
  conversation: { ACTIVE: "Activa" },
  job: { CANCELLED: "Cancelado" },
};

export function enumLabel(
  value: string | null | undefined,
  context?: keyof typeof variants,
) {
  if (value == null || value === "") return "—";
  const overrides = context ? variants[context] : undefined;
  if (overrides && Object.hasOwn(overrides, value)) return overrides[value];
  return Object.hasOwn(labels, value) ? labels[value] : hideTechnicalIds(value);
}

export function operationalMessage(text: string) {
  return text.replace(
    /^(Tu incidencia|La incidencia [A-Z0-9-]+) (?:se encuentra en|tiene el estado) ([A-Z_]+)\.$/u,
    (original: string, subject: string, status: string) => {
      const label = enumLabel(status);
      return label === status
        ? original
        : `${subject} está ${label[0].toLocaleLowerCase("es-PE")}${label.slice(1)}.`;
    },
  );
}

// Localize only fields that represent API enums in read-only audit and diagnostic views.
const enumFields = new Set([
  "status",
  "previousStatus",
  "newStatus",
  "role",
  "type",
  "category",
  "urgency",
  "sentiment",
  "classificationSource",
  "actorType",
  "sourceType",
  "capability",
  "action",
  "entityType",
  "availability",
  "providerVerification",
  "errorCode",
  "errorSummary",
  "lastError",
]);

export function localizeEnumFields(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(localizeEnumFields);
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(
    Object.entries(value).map(([key, field]: [string, unknown]) => [
      key,
      typeof field === "string" && enumFields.has(key)
        ? enumLabel(field)
        : localizeEnumFields(field),
    ]),
  );
}
